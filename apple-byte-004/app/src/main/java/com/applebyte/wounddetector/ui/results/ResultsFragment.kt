package com.applebyte.wounddetector.ui.results

import android.graphics.BitmapFactory
import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import androidx.fragment.app.Fragment
import com.applebyte.wounddetector.databinding.FragmentResultsBinding
import com.applebyte.wounddetector.ui.main.MainActivity
import java.io.File
import java.text.DecimalFormat

class ResultsFragment : Fragment() {

    private var _binding: FragmentResultsBinding? = null
    private val binding get() = _binding!!

    private var woundAreaMm2: Double = 0.0
    private var woundDepthMm: Double = 0.0
    private var imagePath: String = ""

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        arguments?.let {
            woundAreaMm2 = it.getDouble(ARG_AREA)
            woundDepthMm = it.getDouble(ARG_DEPTH)
            imagePath = it.getString(ARG_IMAGE, "")
        }
    }

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View {
        _binding = FragmentResultsBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        setupUI()
    }

    private fun setupUI() {
        val decimalFormat = DecimalFormat("#.##")

        binding.areaValueText.text = "${decimalFormat.format(woundAreaMm2)} mm²"
        binding.depthValueText.text = "${decimalFormat.format(woundDepthMm)} mm"

        if (imagePath.isNotEmpty()) {
            try {
                val file = File(imagePath)
                if (file.exists()) {
                    val bitmap = BitmapFactory.decodeFile(imagePath)
                    binding.resultImage.setImageBitmap(bitmap)
                }
            } catch (e: Exception) {
                e.printStackTrace()
            }
        }

        binding.newScanButton.setOnClickListener {
            (activity as? MainActivity)?.navigateToWelcome()
        }

        binding.saveButton.setOnClickListener {
            saveResults()
        }
    }

    private fun saveResults() {
        try {
            val results = buildString {
                appendLine("=== Apple Wound Analysis Results ===")
                appendLine()
                appendLine("Wound Area: ${String.format("%.2f", woundAreaMm2)} mm²")
                appendLine("Estimated Depth: ${String.format("%.2f", woundDepthMm)} mm")
                appendLine()
                appendLine("Generated by Apple Byte 004")
            }

            val filename = "RESULT_${System.currentTimeMillis()}.txt"
            val file = File(requireContext().cacheDir, filename)
            file.writeText(results)

            android.widget.Toast.makeText(
                requireContext(),
                "Results saved to ${file.name}",
                android.widget.Toast.LENGTH_SHORT
            ).show()

        } catch (e: Exception) {
            e.printStackTrace()
            android.widget.Toast.makeText(
                requireContext(),
                "Failed to save results",
                android.widget.Toast.LENGTH_SHORT
            ).show()
        }
    }

    override fun onDestroyView() {
        super.onDestroyView()
        _binding = null
    }

    companion object {
        private const val ARG_AREA = "area"
        private const val ARG_DEPTH = "depth"
        private const val ARG_IMAGE = "image"

        fun newInstance(areaMm2: Double, depthMm: Double, imagePath: String): ResultsFragment {
            return ResultsFragment().apply {
                arguments = Bundle().apply {
                    putDouble(ARG_AREA, areaMm2)
                    putDouble(ARG_DEPTH, depthMm)
                    putString(ARG_IMAGE, imagePath)
                }
            }
        }
    }
}
