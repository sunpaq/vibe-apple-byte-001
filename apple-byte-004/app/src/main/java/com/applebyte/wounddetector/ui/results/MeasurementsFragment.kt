package com.applebyte.wounddetector.ui.results

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.Toast
import androidx.fragment.app.Fragment
import com.applebyte.wounddetector.databinding.PageMeasurementsBinding
import com.applebyte.wounddetector.ui.main.MainActivity
import java.io.File
import java.text.DecimalFormat

class MeasurementsFragment : Fragment() {

    private var _binding: PageMeasurementsBinding? = null
    private val binding get() = _binding!!

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View {
        _binding = PageMeasurementsBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        
        val parentFragment = parentFragment as? ResultsFragment
        val measurements = parentFragment?.getMeasurements()
        
        measurements?.let { (area, depth, imagePath) ->
            setupUI(area, depth, imagePath)
        } ?: run {
            setupUI(0.0, 0.0, "")
        }
    }

    private fun setupUI(area: Double, depth: Double, imagePath: String) {
        val decimalFormat = DecimalFormat("#.##")

        binding.areaValueText.text = "${decimalFormat.format(area)} mm²"
        binding.depthValueText.text = "${decimalFormat.format(depth)} mm"

        if (imagePath.isNotEmpty()) {
            try {
                val file = File(imagePath)
                if (file.exists()) {
                    val bitmap = android.graphics.BitmapFactory.decodeFile(imagePath)
                    binding.resultImage.setImageBitmap(bitmap)
                }
            } catch (e: Exception) {
                e.printStackTrace()
            }
        }

        binding.newScanButton.setOnClickListener {
            (activity as? MainActivity)?.navigateToWelcome()
        }

        binding.saveButton.setOnClickListener {
            saveResults(area, depth)
        }
    }

    private fun saveResults(area: Double, depth: Double) {
        try {
            val results = buildString {
                appendLine("=== Apple Wound Analysis Results ===")
                appendLine()
                appendLine("Wound Area: ${String.format("%.2f", area)} mm²")
                appendLine("Estimated Depth: ${String.format("%.2f", depth)} mm")
                appendLine()
                appendLine("Generated by Apple Byte 004")
            }

            val filename = "RESULT_${System.currentTimeMillis()}.txt"
            val file = File(requireContext().cacheDir, filename)
            file.writeText(results)

            Toast.makeText(
                requireContext(),
                "Results saved to ${file.name}",
                Toast.LENGTH_SHORT
            ).show()

        } catch (e: Exception) {
            e.printStackTrace()
            Toast.makeText(
                requireContext(),
                "Failed to save results",
                Toast.LENGTH_SHORT
            ).show()
        }
    }

    override fun onDestroyView() {
        super.onDestroyView()
        _binding = null
    }
}
